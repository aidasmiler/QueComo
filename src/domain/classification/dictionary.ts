/**
 * Built-in bilingual (es/en) dictionaries for the rules classifier. Terms are written naturally
 * and normalised when loaded (case, accents, punctuation). A final "s"/"es" plural is matched
 * automatically, so only irregular plurals are listed ("arroces", "nueces").
 *
 * Global catalog ids come from supabase/migrations/20261127120000_recipe_catalogs.sql.
 * Entries with `category: null` / `utensil: null` are blockers: they win as longer phrases and
 * stop a shorter word from matching ("tortilla de trigo" is not an egg dish, "papel de horno"
 * says nothing about the oven).
 */

/** How an ingredient affects vegetarian/vegan suggestions. */
export type DietClass =
  /** Meat, fish, seafood, gelatine: not vegetarian. */
  | 'flesh'
  /** Dairy, eggs, honey: vegetarian, not vegan. */
  | 'animalProduct'
  | 'plant'
  /** Usually plant-based but may contain animal products (pasta, bread, chocolate). */
  | 'plantUnsure'
  /** Cannot tell (stock, generic sauce, processed food). */
  | 'unknown';

export interface Family {
  terms: string[];
  /** Category this family stands for when it is a main ingredient. */
  category?: string;
  /** Weight of a title mention: protein bases and starches decide the dish, vegetables less. */
  titleStrength?: 'strong' | 'normal';
  diet: DietClass;
  /** Contains gluten unless stated otherwise (wheat flour, bread...). */
  gluten?: boolean;
  /** Dairy with lactose unless stated otherwise. */
  lactose?: boolean;
}

